const missing: string[] = [];

for (const [key, value] of Object.entries(env)) {
  if (value === undefined && key !== 'API_WITH_CREDENTIALS') {
    missing.push(`NEXT_PUBLIC_${key}`);
  }
}

if (missing.length > 0) {
  throw new Error(`Missing environment variables:\n${missing.join('\n')}\n\nAdd them to .env.local (copy from .env.example) and restart npm run dev`);
}
